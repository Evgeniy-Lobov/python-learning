# Инициализация списка для хранения сообщений о завершении работы
log_messages = []

try:
# Запрашиваем у пользователя ввод двух чисел
    num1 = input("Введите первое число: ")
    num2 = input("Введите второе число: ")

# Пытаемся преобразовать ввод в числа и выполнить умножение
    result = float(num1) * float(num2)
except ValueError:
    # Обрабатываем ошибку, если ввод не является числом
    print("Ошибка:Введены не числовые значения.")
else:
    # Если нет исключений, выводим результат умножения
    print("Результат умножения:", result)
finally:
    # Записываем информацию о завершении работы
    log_messages.append("Попытка умножения завершена.")
    print("Завершение работы. Сообщение о завершении добавлено в журнал.")

# Выводим сообщения из журнала (для проверки)
    print("\nСообщения журнала:")
    for message in log_messages:
        print(message)