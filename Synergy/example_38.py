# Пример Tkinter, который объединяет все события — нажатие различных кнопок мыши и нажатие
# клавиш на клавиатуре.

# В этом примере мы создадим окно с кнопкой, которая будет реагировать на все указанные события и
# выводить соответствующие сообщения в консоль.

import tkinter as tk

# Функция для обработки нажатий клавиш
def on_key_press(event):
    print(f"Нажата клавиша: {event.char}")

# Функция для обработки кликов мыши
def on_mouse_click(event):
    if event.num == 1:
        print(f"Левая кнопка мыши нажата на координатах ({event.x}, {event.y})")
    elif event.num == 2:
        print(f"Средняя кнопка мыши нажата на координатах ({event.x}, {event.y})")
    elif event.num == 3:
        print(f"Правая кнопка мыши нажата на координатах ({event.x}, {event.y})")

# Создание главного окна
window = tk.Tk()
window.title("Пример обработки событий")

# Создание виджета (кнопки) и размещение его в главном окне
button = tk.Button(window, text="Нажми меня")
button.pack(padx=20, pady=20)

# Привязка событий к главному окну
window.bind("<KeyPress>", on_key_press)  # Привязка события нажатия клавиши
window.bind("<Button-1>", on_mouse_click)  # Привязка события нажатия левой кнопки мыши
window.bind("<Button-2>", on_mouse_click)  # Привязка события нажатия средней кнопки мыши
window.bind("<Button-3>", on_mouse_click)  # Привязка события нажатия правой кнопки мыши

# Запуск главного цикла обработки событий
window.mainloop()
