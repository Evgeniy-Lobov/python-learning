# Создаем список с именем fruits, который содержит три элемента:
#’яблоко’, ’банан’ и ’вишня’
fruits = ['яблоко','банан','вишня']
# Начинаем цикл for, который будет перебирать каждый элемент в списке fruits
for fruit in fruits:
# Для каждого элемента списка fruits выполняем команду print,
# которая выводит элемент (fruit) на экран
    print (fruit)
